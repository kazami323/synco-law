def is_known_type(doc_type: str) -> bool:
    return doc_type in DOCUMENT_TYPES


def type_title(doc_type: str | None) -> str:
    if not doc_type:
        return "Документ"
    return DOCUMENT_TYPES.get(doc_type, {}).get("title", doc_type)


def required_blocks(doc_type: str | None) -> list[str]:
    if not doc_type:
        return []
    return list(DOCUMENT_TYPES.get(doc_type, {}).get("required_blocks", []))


def law_hints(doc_type: str | None) -> list[str]:
    if not doc_type:
        return []
    return list(DOCUMENT_TYPES.get(doc_type, {}).get("law_hints", []))


def catalogue(group: str | None = None) -> list[dict]:
    """Каталог для интерфейса: [{value, title, group, required_blocks}]."""
    items = []
    for value, meta in DOCUMENT_TYPES.items():
        if group and meta.get("group") != group:
            continue
        items.append(
            {
                "value": value,
                "title": meta["title"],
                "group": meta.get("group", "contract"),
                "required_blocks": list(meta.get("required_blocks", [])),
            }
        )
    return items
